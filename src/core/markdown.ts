import type { Analysis, Issue } from './analyze';
import { describeAction, formatDuration, formatOffset, requestDuration } from './describe';
import { redactBody, redactHeaders, redactUrl } from './redact';
import type { ActionEvent, Investigation, RequestEvent } from './types';

/**
 * Plain-Markdown write-up of an investigation, ready to paste into an issue
 * tracker. Everything that leaves the browser goes through `redact*` first.
 */

const fence = (lang: string, body: string) => `\`\`\`${lang}\n${body.replace(/```/g, '`​``')}\n\`\`\``;

function issueLine(i: Issue): string {
  return `- **${i.score}** · \`${i.title.replace(/`/g, "'")}\` — ${i.tag}${i.count > 1 ? ` (×${i.count})` : ''}\n  - ${i.reasons
    .filter((r) => r.points > 0)
    .map((r) => r.text)
    .join('; ')}`;
}

function requestBlock(r: RequestEvent): string {
  const d = requestDuration(r);
  const head = `${r.method} ${redactUrl(r.url)} → ${r.status ?? r.failure?.kind ?? 'pending'}${d !== undefined ? ` · ${formatDuration(d)}` : ''}`;
  const parts = [`**${head}**`];
  const reqHeaders = redactHeaders(r.requestHeaders);
  if (r.postData) parts.push('Request body:', fence('json', redactBody(r.postData) ?? ''));
  if (r.responseBody) parts.push('Response body:', fence('json', redactBody(r.responseBody) ?? ''));
  if (reqHeaders && Object.keys(reqHeaders).length) {
    parts.push(
      '<details><summary>Request headers</summary>\n\n' +
        fence(
          '',
          Object.entries(reqHeaders)
            .map(([k, v]) => `${k}: ${v}`)
            .join('\n'),
        ) +
        '\n</details>',
    );
  }
  return parts.join('\n\n');
}

export function toMarkdown(inv: Investigation, analysis: Analysis): string {
  const out: string[] = [];
  out.push(`# ${inv.title}`);
  out.push(
    `Page: ${redactUrl(inv.pageUrl) || 'unknown'} · Recorded ${new Date(inv.startedAt).toISOString()}` +
      (inv.stoppedAt ? ` · ${formatDuration(inv.stoppedAt - inv.startedAt)}` : ''),
  );
  if (analysis.summary) out.push(`## What happened\n\n${analysis.summary}`);

  const actions = inv.events.filter((e): e is ActionEvent => e.type === 'action').sort((a, b) => a.time - b.time);
  if (actions.length) {
    out.push(
      '## Steps to reproduce\n\n' +
        actions
          .map(
            (a, n) =>
              `${n + 1}. ${describeAction(a)}${a.target ? ` — \`${a.target.selector}\`` : ''} _(+${formatOffset(a.time - inv.startedAt)})_`,
          )
          .join('\n'),
    );
  }

  const top = analysis.issues.filter((i) => !i.noise).slice(0, 10);
  if (top.length) out.push('## Issues, ranked by impact\n\n' + top.map(issueLine).join('\n'));

  const failed = top
    .filter((i) => i.kind === 'request' || i.kind === 'slow')
    .slice(0, 5)
    .map((i) => requestBlock(i.occurrences[0] as RequestEvent));
  if (failed.length) out.push('## Request details\n\n' + failed.join('\n\n'));

  out.push(
    `---\n_Generated by BugTrail. Authorization, cookies, tokens and password-like fields are redacted. ${analysis.counts.requests} requests recorded, ${analysis.counts.noise} noise events hidden._`,
  );
  return out.join('\n\n') + '\n';
}
